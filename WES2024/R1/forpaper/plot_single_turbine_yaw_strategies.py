"""
R1 paper figure: one yawed BEM rotor in uniform flow under the three yaw strategies plus joint control, as a
function of yaw. Six panels: CP, CT, CT' (top row); TSR, pitch, u4 (bottom row).

Symmetry about yaw=0 was checked independently (see tmp/extra/plot_single_turbine_yaw_strategies.py, _rotor at
+/-yaw): Cp, Ct, u4 agree between +yaw and -yaw to ~1e-5%, so plotting 0-45 deg only is representative.

Data is cached in data/generate_single_turbine_yaw_strategies.csv (generated by
WES2024/R1/generate/generate_single_turbine_yaw_strategies.py, 0-45 deg of yaw). Cp is a very flat ridge in (pitch, tsr)
at large yaw, so pitch/TSR of the Joint strategy are only weakly determined there (see that file for the caveat).

Usage: python -m WES2024.R1.forpaper.plot_single_turbine_yaw_strategies
"""

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import polars as pl

from WES2024.R1 import figuresettings as fs

# CSV = utils.CACHEDIR / "generate_single_turbine_yaw_strategies.csv"

# order matches the legend requested for this figure
KEY = {"YawMod": "YawModControl", "YawKOmega": "YawKOmegaControl", "Yaw": "YawControl", "Joint": "JointControl"}
COSINE = {"Cp": 3, "Ct": 2, "Ctprime": -2, "tsr": 1}  # "classical" reference scalings of the unyawed value


def plot(df):
    panels = [
        ("Cp", r"$C_P$"),
        ("Ct", r"$C_T$"),
        ("Ctprime", r"$C_T'$"),
        ("tsr", r"$\lambda$"),
        ("pitch", r"$\theta_p$ (deg)"),
        # ("u4", r"$u_4 / u_\infty$"),
        ("du", r"$|\delta u_0| / u_\infty$"),
    ]
    yaw_max = df["yaw"].max()
    fig, axs = plt.subplots(2, 3, figsize=(6.5, 3.5), sharex=True)
    j = 97
    for ax, (col, label) in zip(axs.flat, panels):
        lines = []
        for m, k in KEY.items():
            d = df.filter(pl.col("method") == m).sort("yaw")
            line, = ax.plot(d["yaw"], d[col], color=fs.CONTROLLER_COLORS[k], ls=fs.CONTROLLER_LINESTYLES[k],
                            label=fs.controller_labels[k])
            lines.append(line)
        if col in COSINE:  # unyawed value x cos^p(yaw)
            d0 = df.filter((pl.col("method") == "Yaw") & (pl.col("yaw") == 0.0))[col][0]
            y = np.linspace(0, yaw_max, 100)
            cos_label = rf"$\cos^{{{COSINE[col]}}}(\gamma)$" if COSINE[col] != 1 else r"$\cos(\gamma)$"
            cos_line, = ax.plot(y, d0 * np.cos(np.deg2rad(y)) ** COSINE[col], color="0.7", ls=":", lw=2.5,
                                 label=cos_label)
            ax.legend(handles=[cos_line], fontsize=8, loc="best", frameon=False)
        ax.set_ylabel(label)
        ax.set_xlim(0, yaw_max)
        ax.text(-0.22, 1.0, f"({chr(j)})", transform=ax.transAxes, fontsize=10, ha="right", va="center")
        j += 1

    for ax in axs[1, :]:
        ax.set_xlabel("Yaw (deg)")

    fig.tight_layout(rect=(0, 0.1, 1, 1))
    fig.legend(handles=lines, loc="lower center", ncol=4, bbox_to_anchor=(0.5, 0.0), frameon=False, fontsize=8)
    fs.save()


if __name__ == "__main__":
    from WES2024.R1.generate import generate_single_turbine_yaw_strategies
    df = generate_single_turbine_yaw_strategies.generate().with_columns(
        (1 - pl.col("u4")).alias("du")
    )
    plot(df)
